const CATALOGUES: Record<UiLocale, Record<ApiMessageKey, string>> = {
  'zh-CN': apiMessagesZh,
  en: apiMessagesEn,
};

export function apiCatalogue(locale: UiLocale): Record<ApiMessageKey, string> {
  return CATALOGUES[locale] ?? CATALOGUES['zh-CN'];
}

export type ApiMessageParams = Record<string, string | number>;

export function apiT(
  locale: UiLocale,
  key: ApiMessageKey,
  params?: ApiMessageParams,
): string {
  const template = apiCatalogue(locale)[key] ?? apiMessagesZh[key] ?? key;
  return formatMessage(template, params);
}
