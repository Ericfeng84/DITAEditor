/**
 * PDF theme -> DITA-OT `--customization.dir` materialisation (Phase 15).
 *
 * DITA-OT's PDF2 plug-in resolves three XSLT resources through the XML catalog
 * (`cfg:fo/attrs/custom.xsl`, `cfg:fo/xsl/custom.xsl`,
 * `cfg:fo/font-mappings.xml`). `<customization.dir>/catalog.xml` is placed first
 * in the catalog path, so a job-local directory can point those URIs at the
 * exported theme assets without installing a plug-in.
 *
 * The generated `custom.xsl` files use `xsl:import` chains instead of copying
 * theme XSLT into the job directory:
 *
 *   attrs/custom.xsl = import (attrs-base) -> import (theme attrs) -> import (theme-vars)
 *   xsl/custom.xsl   = the same three imports + `xsl:include` (xsl-base)
 *
 * `xsl:include` (not import) is used for `xsl-base.xsl` because an imported
 * module's variable references bind lexically to *its own* imports; including
 * it merges the structural overrides into the customization module, whose
 * import chain carries the job-specific tokens (`$de-font-size`,
 * `$de-page-width`, `$de-mirror-margins`, ...).
 *
 * Nothing here ever mutates the shared checkout: every file is written below
 * `<publishRoot>/jobs/<id>/customization`. User supplied XSLT paths are not
 * supported by design - only the exported, static theme assets are imported.
 */
import { copyFile, mkdir, stat, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { checkXmlWellFormed } from '@dita/core';
import { httpError } from '../errors.js';
import { resolveSafeWorkspacePath } from '../files/workspace-fs.js';
import {
  PDF_LOGO_EXTENSIONS,
  PDF_LOGO_MAX_BYTES,
  PDF_MARGIN_PRESETS,
  PDF_PAGE_GEOMETRY,
  pdfThemeColors,
  pdfThemeDefinition,
  resolvePdfTheme,
  resolvePdfThemesDir,
  toFoColor,
  type PdfThemeColors,
  type PdfThemeId,
  type PdfThemeOptions,
  type ResolvedPdfTheme,
} from './pdf-themes.js';

export interface PdfCustomizationInput {
  /** Absolute job directory (`<publishRoot>/jobs/<id>`). */
  jobDir: string;
  /** Materialised source tree the `logoPath` is resolved against. */
  snapshotDir: string;
  themeId: PdfThemeId;
  themeOptions: PdfThemeOptions | null | undefined;
  /** Overrides `resolvePdfThemesDir()` in tests. */
  themesDir?: string;
  /** `com.ditaeditor.pdf-cjk` plugin directory (CJK font mappings + vanilla). */
  pluginDir: string;
}

export interface PdfCustomizationResult {
  /** Value for `--customization.dir`. */
  customizationDir: string;
  /** Extra DITA-OT CLI arguments implied by the theme features. */
  extraDitaArgs: string[];
  /** Non-fatal problems (e.g. rejected logo) to append to the build log. */
  warnings: string[];
}

const FONT_MAPPINGS_RELATIVE = join('cfg', 'fo', 'font-mappings.xml');

/**
 * Validate generated (or exported) XML before handing it to DITA-OT: a single
 * malformed catalog/XSLT file fails the whole PDF build with an XSLT error that
 * is very hard to trace back, so we fail early with the file name.
 */
function assertWellFormed(xml: string, fileName: string): void {
  const result = checkXmlWellFormed(xml);
  if (!result.ok) {
    const detail = result.error
      ? `${result.error.message} (line ${result.error.line}, column ${result.error.column})`
      : 'unknown XML error';
    throw new Error(`Generated PDF theme asset is not well-formed: ${fileName}: ${detail}`);
  }
}

function xmlEscapeText(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function xslString(value: string): string {
  return `'${xmlEscapeText(value).replace(/'/g, "''")}'`;
}

function xslBoolean(value: boolean): string {
  return value ? 'true()' : 'false()';
}

interface ThemeVariable {
  name: string;
  value: string;
  comment?: string;
}

function renderVariables(variables: readonly ThemeVariable[]): string {
  return variables
    .map((variable) => {
      const comment = variable.comment ? `  <!-- ${variable.comment} -->\n` : '';
      return `${comment}  <xsl:variable name="${variable.name}" select="${variable.value}"/>\n`;
    })
    .join('\n');
}

function renderStylesheet(
  header: string,
  imports: readonly string[],
  body = '',
  includes: readonly string[] = [],
): string {
  const importLines = imports
    .map((href) => `  <xsl:import href="${xmlEscapeText(href)}"/>`)
    .concat(includes.map((href) => `  <xsl:include href="${xmlEscapeText(href)}"/>`))
    .join('\n');
  const bodyBlock = body ? `\n${body}` : '';
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by DITAEditor (Phase 15 PDF themes). Do not edit by hand. -->',
    header,
    '<xsl:stylesheet version="3.0" xmlns:xsl="http://www.w3.org/1999/XSL/Transform"',
    '                xmlns:fo="http://www.w3.org/1999/XSL/Format"',
    '                xmlns:xs="http://www.w3.org/2001/XMLSchema"',
    '                xmlns:opentopic="http://www.ibm.com/iibm/xml/opentopic"',
    '                exclude-result-prefixes="#all">',
    importLines,
    `${bodyBlock}</xsl:stylesheet>`,
    '',
  ].join('\n');
}

function fileUri(path: string): string {
  return pathToFileURL(path).href;
}

/**
 * `theme-vars.xsl` carries the resolved job options as XSLT variables. It is
 * imported last (highest precedence) so user choices win over the theme's own
 * defaults in `attrs.xsl`.
 */
function renderThemeVars(
  themeId: PdfThemeId,
  resolved: ResolvedPdfTheme,
  colors: PdfThemeColors,
  coverStyle: string,
  logoUri: string | null,
): string {
  const { options, features, pageSize, fontFamily, fontSize, margins, fontKey } = resolved;
  const geometry = PDF_PAGE_GEOMETRY[pageSize];
  const preset = PDF_MARGIN_PRESETS[margins];
  // Without mirrored margins the outer margin has no meaning; keep the text
  // block symmetric instead of shifting every page one way.
  const outside = features.mirrorMargins ? preset.outside : preset.inside;

  const variables: ThemeVariable[] = [
    { name: 'de-page-width', value: xslString(geometry.width), comment: `page size ${pageSize}` },
    { name: 'de-page-height', value: xslString(geometry.height) },
    { name: 'de-page-margin-inside', value: xslString(preset.inside), comment: `margins ${margins}` },
    { name: 'de-page-margin-outside', value: xslString(outside) },
    { name: 'de-page-margin-top', value: xslString(preset.top) },
    { name: 'de-page-margin-bottom', value: xslString(preset.bottom) },
    { name: 'de-font-size', value: xslString(fontSize), comment: `body ${fontFamily} ${fontSize}` },
    { name: 'de-font-family', value: xslString(fontKey === 'serif' ? 'Serif' : 'Sans') },
    { name: 'de-accent', value: xslString(toFoColor(colors.accent)) },
    { name: 'de-accent-soft', value: xslString(toFoColor(colors.accentSoft)) },
    { name: 'de-accent-border', value: xslString(toFoColor(colors.accentBorder)) },
    { name: 'de-accent-contrast', value: xslString(colors.accentContrast) },
    { name: 'de-cover-enabled', value: xslBoolean(features.showCover), comment: 'feature flags' },
    { name: 'de-toc-enabled', value: xslBoolean(features.showToc) },
    { name: 'de-chapter-numbers', value: xslBoolean(features.chapterNumbers) },
    { name: 'de-task-labels', value: xslBoolean(features.taskLabels) },
    { name: 'de-mirror-margins', value: xslBoolean(features.mirrorMargins) },
    { name: 'de-cover-style', value: xslString(coverStyle) },
    { name: 'de-cover-subtitle', value: xslString(options.coverSubtitle ?? '') },
    { name: 'de-header-text', value: xslString(options.headerText ?? '') },
    { name: 'de-footer-text', value: xslString(options.footerText ?? '') },
    { name: 'de-logo-uri', value: xslString(logoUri ?? ''), comment: 'logo (empty = none)' },
  ];

  return renderStylesheet(
    `<!-- PDF theme: ${themeId} -->`,
    [],
    `\n${renderVariables(variables)}`,
  );
}

function renderCatalog(): string {
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by DITAEditor (Phase 15 PDF themes). Do not edit by hand. -->',
    '<catalog xmlns="urn:oasis:names:tc:entity:xmlns:xml:catalog" prefer="system">',
    `  <uri name="cfg:fo/font-mappings.xml" uri="${FONT_MAPPINGS_RELATIVE.split('\\').join('/')}"/>`,
    '  <uri name="cfg:fo/attrs/custom.xsl" uri="fo/attrs/custom.xsl"/>',
    '  <uri name="cfg:fo/xsl/custom.xsl" uri="fo/xsl/custom.xsl"/>',
    '</catalog>',
    '',
  ].join('\n');
}

interface LogoResolution {
  logoUri: string | null;
  warnings: string[];
}

/**
 * Resolve, validate and stage the cover logo.
 *
 * FOP 2.9 cannot decode WebP, so the extension whitelist is explicit; failures
 * never fail the build - the cover simply renders without a logo.
 */
async function stageLogo(
  input: PdfCustomizationInput,
  artworkDir: string,
): Promise<LogoResolution> {
  const raw = input.themeOptions?.logoPath?.trim();
  if (!raw) return { logoUri: null, warnings: [] };
  const warnings: string[] = [];
  const reject = (reason: string): LogoResolution => {
    warnings.push(`logo '${raw}' ignored: ${reason}`);
    return { logoUri: null, warnings };
  };
  const extension = raw.slice(raw.lastIndexOf('.')).toLowerCase();
  if (!PDF_LOGO_EXTENSIONS.includes(extension)) {
    return reject(
      `unsupported file type '${extension || 'unknown'}' (expected ${PDF_LOGO_EXTENSIONS.join(', ')})`,
    );
  }
  let source: string;
  try {
    source = (await resolveSafeWorkspacePath(input.snapshotDir, raw)).absPath;
  } catch {
    return reject('path escapes the project workspace');
  }
  if (!existsSync(source)) return reject('file not found');
  const info = await stat(source);
  if (!info.isFile()) return reject('not a regular file');
  if (info.size > PDF_LOGO_MAX_BYTES) {
    return reject(`file is larger than ${Math.round(PDF_LOGO_MAX_BYTES / 1024)} KB`);
  }
  const target = join(artworkDir, `logo${extension}`);
  await copyFile(source, target);
  return { logoUri: fileUri(target), warnings };
}

/**
 * Materialise the job-local PDF customization directory.
 *
 * `vanilla` returns the CJK plug-in directory unchanged so the publish output
 * matches pre-Phase-15 behaviour byte for byte.
 */
export async function preparePdfCustomizationDir(
  input: PdfCustomizationInput,
): Promise<PdfCustomizationResult> {
  const definition = pdfThemeDefinition(input.themeId);
  const resolved = resolvePdfTheme(input.themeId, input.themeOptions);
  if (!definition.supportsCustomization) {
    return { customizationDir: input.pluginDir, extraDitaArgs: [], warnings: [] };
  }

  let themesDir: string;
  try {
    themesDir = resolvePdfThemesDir(input.themesDir);
  } catch {
    throw httpError(500, 'publish.pdfThemeAssetsMissing', undefined, {
      themeId: input.themeId,
      asset: input.themesDir ?? 'dita-ot-plugins/pdf-themes',
    });
  }
  const sharedAttrs = join(themesDir, 'shared', 'attrs-base.xsl');
  const sharedXsl = join(themesDir, 'shared', 'xsl-base.xsl');
  const themeAttrs = join(themesDir, input.themeId, 'attrs.xsl');
  const fontMappings = join(input.pluginDir, FONT_MAPPINGS_RELATIVE);
  for (const required of [sharedAttrs, sharedXsl, themeAttrs, fontMappings]) {
    if (!existsSync(required)) {
      throw httpError(500, 'publish.pdfThemeAssetsMissing', undefined, {
        themeId: input.themeId,
        asset: required,
      });
    }
  }

  const customizationDir = join(input.jobDir, 'customization');
  const attrsDir = join(customizationDir, 'fo', 'attrs');
  const xslDir = join(customizationDir, 'fo', 'xsl');
  const fontDir = join(customizationDir, 'cfg', 'fo');
  const artworkDir = join(customizationDir, 'common', 'artwork');
  for (const dir of [attrsDir, xslDir, fontDir, artworkDir]) {
    await mkdir(dir, { recursive: true });
  }

  // 1. CJK font mappings must survive every theme, otherwise Simplified
  //    Chinese PDFs fall back to a font without the required glyphs.
  await copyFile(fontMappings, join(fontDir, 'font-mappings.xml'));

  // 2. Cover logo (optional, best effort).
  const logo = await stageLogo(input, artworkDir);

  // 3. Job-specific variables.
  const varsPath = join(attrsDir, 'theme-vars.xsl');
  const varsXml = renderThemeVars(
    input.themeId,
    resolved,
    pdfThemeColors(resolved.accent),
    definition.coverStyle,
    logo.logoUri,
  );
  assertWellFormed(varsXml, 'fo/attrs/theme-vars.xsl');
  await writeFile(varsPath, varsXml, 'utf8');

  // 4. Attribute sets and structural overrides.
  const chain = [fileUri(sharedAttrs), fileUri(themeAttrs), fileUri(varsPath)];
  const attrsXml = renderStylesheet(
    `<!-- PDF theme attribute sets: ${input.themeId} -->`,
    chain,
  );
  assertWellFormed(attrsXml, 'fo/attrs/custom.xsl');
  await writeFile(join(attrsDir, 'custom.xsl'), attrsXml, 'utf8');

  // Importing the generated attribute-set stylesheet (instead of repeating the same three
  // imports) keeps every module single-imported; `xsl:include` then merges the structural
  // overrides into this module so they inherit that import chain.
  const xslXml = renderStylesheet(
    `<!-- PDF theme overrides: ${input.themeId} -->`,
    [fileUri(join(attrsDir, 'custom.xsl'))],
    '',
    [fileUri(sharedXsl)],
  );
  assertWellFormed(xslXml, 'fo/xsl/custom.xsl');
  await writeFile(join(xslDir, 'custom.xsl'), xslXml, 'utf8');

  // 5. Catalog redirecting pdf2's URIs at the staged files.
  const catalogXml = renderCatalog();
  assertWellFormed(catalogXml, 'catalog.xml');
  await writeFile(join(customizationDir, 'catalog.xml'), catalogXml, 'utf8');

  return {
    customizationDir,
    extraDitaArgs: resolved.features.taskLabels ? ['--args.gen.task.lbl=YES'] : [],
    warnings: logo.warnings,
  };
}
