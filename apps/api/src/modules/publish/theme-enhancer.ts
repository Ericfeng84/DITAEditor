/**
 * CSS emitted as `_ditaeditor/brand-vars.css`. Loaded last, so its accent
 * tokens win over the theme stylesheet while the remaining tokens inherit the
 * theme's own palette.
 */
export function buildBrandVarsCss(themeId: HtmlThemeId, options: HtmlThemeOptions): string {
  const descriptor = getHtmlTheme(themeId, 'en');
  const scale = accentScale(options.accentColor ?? descriptor?.defaultAccent ?? '#2563eb');
  return [
    '/* Generated by DITAEditor from the publish theme options. */',
    ':root[data-de-theme] {',
    `  --de-accent: ${scale.accent};`,
    `  --de-accent-hover: ${scale.hover};`,
    `  --de-accent-soft: ${scale.soft};`,
    `  --de-accent-border: ${scale.border};`,
    `  --de-accent-contrast: ${scale.contrast};`,
    '  --de-link: var(--de-accent);',
    '  --de-link-hover: var(--de-accent-hover);',
    '  --de-focus-color: var(--de-accent);',
    '  --de-active-bg: var(--de-accent-soft);',
    '  --de-bar: var(--de-accent);',
    '}',
    '',
  ].join('\n');
}

/* -------------------------------------------------------------------------- */
/* HTML text extraction (search index)                                         */
/* -------------------------------------------------------------------------- */

function decodeEntities(value: string): string {
  return value.replace(/&(#x?[0-9a-fA-F]+|[a-zA-Z]+);/g, (match, entity: string) => {
    if (entity.startsWith('#x') || entity.startsWith('#X')) {
      const code = Number.parseInt(entity.slice(2), 16);
      return Number.isFinite(code) ? String.fromCodePoint(code) : match;
    }
    if (entity.startsWith('#')) {
      const code = Number.parseInt(entity.slice(1), 10);
      return Number.isFinite(code) ? String.fromCodePoint(code) : match;
    }
    return HTML_ENTITIES[entity.toLowerCase()] ?? match;
  });
}

function collapseWhitespace(value: string): string {
  return value.replace(/\s+/g, ' ').trim();
}

function stripTags(value: string): string {
  return collapseWhitespace(decodeEntities(value.replace(/<[^>]*>/g, ' ')));
}

function elementOpeners(html: string, tag: string): { open: string; inner: string }[] {
  const pattern = new RegExp(`<${tag}\\b([^>]*)>([\\s\\S]*?)<\\/${tag}>`, 'gi');
  const found: { open: string; inner: string }[] = [];
  let match: RegExpExecArray | null = pattern.exec(html);
  while (match) {
    found.push({ open: match[0]!.slice(0, match[0]!.indexOf('>') + 1), inner: match[2]! });
    match = pattern.exec(html);
  }
  return found;
}

function extractTitle(html: string): string {
  const h1s = elementOpeners(html, 'h1');
  const topical = h1s.find((entry) => /class\s*=\s*["'][^"']*topictitle1/i.test(entry.open));
  const heading = topical ?? h1s[0];
  if (heading) {
    const text = stripTags(heading.inner);
    if (text) return text;
  }
  const title = /<title\b[^>]*>([\s\S]*?)<\/title>/i.exec(html);
  return title ? stripTags(title[1]!) : '';
}

function stripSiteSuffix(title: string, siteTitle: string): string {
  if (!siteTitle) return title;
  for (const separator of [' - ', ' | ', ' – ', ' — ', ' · ']) {
    const suffix = `${separator}${siteTitle}`;
    if (title.endsWith(suffix)) {
      return title.slice(0, title.length - suffix.length).trim();
    }
  }
  return title;
}

function extractShortdesc(html: string): string {
  for (const tag of ['div', 'p', 'section']) {
    for (const entry of elementOpeners(html, tag)) {
      if (!/class\s*=\s*["'][^"']*shortdesc/i.test(entry.open)) continue;
      const text = stripTags(entry.inner);
      if (text) return text;
    }
  }
  return extractMetaDescription(html);
}

function extractMetaDescription(html: string): string {
  const metaPattern = /<meta\b[^>]*>/gi;
  let match: RegExpExecArray | null = metaPattern.exec(html);
  while (match) {
    const tag = match[0]!;
    const name = /\bname\s*=\s*["']([^"']*)["']/i.exec(tag)?.[1]?.toLowerCase();
    if (name === 'description') {
      const content = /\bcontent\s*=\s*["']([^"']*)["']/i.exec(tag)?.[1];
      if (content) return collapseWhitespace(decodeEntities(content));
    }
    match = metaPattern.exec(html);
  }
  return '';
}

function extractBodyText(html: string): string {
  const main = /<main\b[^>]*>([\s\S]*?)<\/main>/i.exec(html);
  const region = main?.[1] ?? /<body\b[^>]*>([\s\S]*)<\/body>/i.exec(html)?.[1] ?? html;
  const withoutChrome = region
    .replace(/<script\b[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style\b[\s\S]*?<\/style>/gi, ' ')
    .replace(/<nav\b[\s\S]*?<\/nav>/gi, ' ')
    .replace(/<header\b[\s\S]*?<\/header>/gi, ' ')
    .replace(/<footer\b[\s\S]*?<\/footer>/gi, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ');
  return stripTags(withoutChrome).slice(0, SEARCH_TEXT_LIMIT);
}

function buildSearchEntry(
  href: string,
  html: string,
  siteTitle: string,
): HtmlThemeSearchEntry {
  const title = stripSiteSuffix(extractTitle(html), siteTitle);
  return {
    href,
    title,
    summary: extractShortdesc(html),
    text: extractBodyText(html),
  };
}

/* -------------------------------------------------------------------------- */
/* Workspace asset containment                                                 */
/* -------------------------------------------------------------------------- */

function resolveWorkspaceFile(workspaceRoot: string, relPath: string): string {
  if (relPath.includes('\0')) throw new Error('path contains null bytes');
  const normalized = relPath.replace(/\\/g, '/').trim();
  if (!normalized) throw new Error('path is empty');
  if (normalized.startsWith('/') || /^[a-zA-Z]:/.test(normalized)) {
    throw new Error('absolute paths are not permitted');
  }
  const root = resolve(workspaceRoot);
  const abs = resolve(root, ...normalized.split('/'));
  const rel = relative(root, abs);
  if (!rel || rel === '..' || rel.startsWith(`..${sep}`) || isAbsolute(rel)) {
    throw new Error('path escapes the workspace');
  }
  if (!existsSync(abs) || !statSync(abs).isFile()) {
    throw new Error('file does not exist');
  }
  return abs;
}

