interface InjectionContext {
  themeId: HtmlThemeId;
  relRoot: string;
  portal: boolean;
  siteTitle: string;
  footerText: string;
  defaultMode: 'light' | 'dark';
  features: HtmlThemeFeatures;
  locale: ApiLocale;
  logoName: string | null;
  hasCustomCss: boolean;
}

function themeConfigScript(context: InjectionContext): string {
  const config = {
    themeId: context.themeId,
    locale: context.locale,
    siteTitle: context.siteTitle,
    defaultMode: context.defaultMode,
    portal: context.portal,
    features: context.features,
    labels: HTML_THEME_LABELS[context.locale],
  };
  return `<script>window.__DITA_THEME_CONFIG__ = ${serializeInlineJson(config)};</script>`;
}

function headMarkup(context: InjectionContext): string {
  const base = `${context.relRoot}${THEME_ASSET_DIR}`;
  const links = [
    `<link rel="stylesheet" href="${base}/theme-base.css">`,
    `<link rel="stylesheet" href="${base}/theme.css">`,
    `<link rel="stylesheet" href="${base}/brand-vars.css">`,
  ];
  if (context.hasCustomCss) {
    links.push(`<link rel="stylesheet" href="${base}/custom.css">`);
  }
  return `${links.join('\n')}\n${themeConfigScript(context)}\n`;
}

function headerMarkup(context: InjectionContext): string {
  const base = `${context.relRoot}${THEME_ASSET_DIR}`;
  const logo = context.logoName
    ? `<img class="de-logo" src="${base}/${context.logoName}" alt="">`
    : '';
  const shortcut = escapeHtmlText(HTML_THEME_LABELS[context.locale].shortcutHint);
  return [
    '<header class="de-header">',
    `<a class="de-brand" href="${context.relRoot}index.html">`,
    logo,
    `<span class="de-brand-title">${escapeHtmlText(context.siteTitle)}</span>`,
    '</a>',
    '<div class="de-header-actions">',
    '<button class="de-icon-btn de-search-trigger" type="button" data-de="search-trigger">',
    `<span class="de-kbd">${shortcut}</span>`,
    '</button>',
    '<button class="de-icon-btn de-mode-toggle" type="button" data-de="mode-toggle"></button>',
    '</div>',
    '<button class="de-icon-btn de-nav-toggle" type="button" data-de="nav-toggle"></button>',
    '</header>',
  ].join('');
}

function footerMarkup(context: InjectionContext): string {
  const base = `${context.relRoot}${THEME_ASSET_DIR}`;
  return [
    `<footer class="de-footer"><p>${escapeHtmlText(context.footerText)}</p></footer>`,
    '<div class="de-search" data-de="search" hidden></div>',
    '<div class="de-backdrop" data-de="backdrop" hidden></div>',
    `<script defer src="${base}/search-index.js"></script>`,
    `<script defer src="${base}/theme-runtime.js"></script>`,
    '',
  ].join('\n');
}

function appendBodyClasses(bodyOpen: string, classes: string[]): string {
  const classMatch = /(\sclass\s*=\s*)(["'])([\s\S]*?)\2/i.exec(bodyOpen);
  if (classMatch) {
    const existing = classMatch[3]!.trim().split(/\s+/).filter(Boolean);
    for (const name of classes) {
      if (!existing.includes(name)) existing.push(name);
    }
    const merged = `${classMatch[1]}${classMatch[2]}${existing.join(' ')}${classMatch[2]}`;
    return bodyOpen.replace(classMatch[0], merged);
  }
  return bodyOpen.replace(/>$/, ` class="${classes.join(' ')}">`);
}

/**
 * Inject the theme into one page. Returns `null` when the page is already
 * enhanced (idempotent re-runs) or is missing the anchors we must not corrupt.
 */
function injectPage(
  html: string,
  relPath: string,
  context: InjectionContext,
  warn: (message: string) => void,
): string | null {
  const htmlOpen = /<html\b[^>]*>/i.exec(html);
  if (!htmlOpen) {
    warn(`html page skipped (no <html> tag): ${relPath}`);
    return null;
  }
  // Only the <html> tag counts as "already enhanced": a topic may legitimately
  // document the `data-de-theme` attribute inside a code block.
  if (/\bdata-de-theme\s*=/i.test(htmlOpen[0])) return null;
  if (!/<\/head>/i.test(html) || !/<\/body>/i.test(html)) {
    warn(`html page skipped (missing </head> or </body>): ${relPath}`);
    return null;
  }
  const bodyOpen = /<body\b[^>]*>/i.exec(html);
  if (!bodyOpen) {
    warn(`html page skipped (no <body> tag): ${relPath}`);
    return null;
  }

  const htmlAttrs = [
    `data-de-theme="${context.themeId}"`,
    `data-de-root="${context.relRoot}"`,
    `data-de-mode="${context.defaultMode}"`,
    `data-de-portal="${context.portal ? 'true' : 'false'}"`,
  ].join(' ');
  const nextHtmlOpen = htmlOpen[0].replace(/>$/, ` ${htmlAttrs}>`);

  const bodyClasses = [`de-theme-${context.themeId}`];
  if (context.portal) bodyClasses.push('de-portal');
  const nextBodyOpen = appendBodyClasses(bodyOpen[0], bodyClasses);

  // Function replacements: a site title may legitimately contain `$&` or
  // `$'`, which a string replacement would treat as substitution patterns.
  return html
    .replace(htmlOpen[0], () => nextHtmlOpen)
    .replace(bodyOpen[0], () => `${nextBodyOpen}${headerMarkup(context)}`)
    .replace(/<\/head>/i, () => `${headMarkup(context)}</head>`)
    .replace(/<\/body>/i, () => `${footerMarkup(context)}</body>`);
}

