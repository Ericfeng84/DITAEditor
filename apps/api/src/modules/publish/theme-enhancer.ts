async function collectHtmlFiles(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name));
  const files: string[] = [];
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (entry.name === THEME_ASSET_DIR) continue;
      files.push(...(await collectHtmlFiles(join(dir, entry.name))));
    } else if (entry.isFile() && entry.name.toLowerCase().endsWith('.html')) {
      files.push(join(dir, entry.name));
    }
  }
  return files;
}

function toPosix(value: string): string {
  return value.split(sep).join('/');
}

function depthOf(relPath: string): number {
  return relPath.split('/').length - 1;
}

async function copySharedAsset(
  sourceDir: string,
  outputDir: string,
  fileName: string,
  assets: string[],
  warn: (message: string) => void,
): Promise<void> {
  const source = join(sourceDir, fileName);
  if (!existsSync(source)) {
    warn(`theme asset missing: ${source}`);
    return;
  }
  await copyFile(source, join(outputDir, THEME_ASSET_DIR, fileName));
  assets.push(`${THEME_ASSET_DIR}/${fileName}`);
}

async function copyWorkspaceAsset(
  workspaceRoot: string,
  relPath: string,
  outputDir: string,
  targetName: string,
  options: { extensions: Set<string>; maxBytes: number; label: string },
  warn: (message: string) => void,
): Promise<string | null> {
  let abs: string;
  try {
    abs = resolveWorkspaceFile(workspaceRoot, relPath);
  } catch (err) {
    warn(`${options.label} skipped (${relPath}): ${err instanceof Error ? err.message : String(err)}`);
    return null;
  }
  const extension = extname(abs).toLowerCase();
  if (!options.extensions.has(extension)) {
    warn(`${options.label} skipped (${relPath}): unsupported file type ${extension || '(none)'}`);
    return null;
  }
  const info = await stat(abs);
  if (info.size > options.maxBytes) {
    warn(`${options.label} skipped (${relPath}): file exceeds ${options.maxBytes} bytes`);
    return null;
  }
  const name = targetName.replace('{ext}', extension);
  await copyFile(abs, join(outputDir, THEME_ASSET_DIR, name));
  return name;
}

export async function enhanceHtml5Output(o: EnhanceHtml5Options): Promise<Html5EnhanceResult> {
  const warnings: string[] = [];
  const warn = (message: string) => {
    warnings.push(message);
    o.onWarn?.(message);
  };
  const baseResult: Html5EnhanceResult = {
    themeId: o.themeId,
    pages: 0,
    assets: [],
    searchEntries: [],
    warnings,
    logo: null,
    customCss: null,
  };

  if (o.themeId === 'vanilla') {
    return baseResult;
  }

  const descriptor = getHtmlTheme(o.themeId, o.locale);
  if (!descriptor) {
    warn(`unknown html theme: ${o.themeId}`);
    return baseResult;
  }

  const options = resolveThemeOptions(o.options);
  const features: HtmlThemeFeatures = { ...DEFAULT_HTML_FEATURES, ...options.features };
  const assetDir = join(o.outputDir, THEME_ASSET_DIR);
  await mkdir(assetDir, { recursive: true });

  const assets: string[] = [];
  await copySharedAsset(join(o.themesDir, 'shared'), o.outputDir, 'theme-base.css', assets, warn);
  await copySharedAsset(join(o.themesDir, o.themeId), o.outputDir, 'theme.css', assets, warn);
  await copySharedAsset(join(o.themesDir, 'shared'), o.outputDir, 'theme-runtime.js', assets, warn);

  await writeFile(join(assetDir, 'brand-vars.css'), buildBrandVarsCss(o.themeId, options), 'utf8');
  assets.push(`${THEME_ASSET_DIR}/brand-vars.css`);

  const logoName = options.logoPath
    ? await copyWorkspaceAsset(
        o.workspaceRoot,
        options.logoPath,
        o.outputDir,
        'logo{ext}',
        { extensions: LOGO_EXTENSIONS, maxBytes: THEME_LOGO_LIMIT_BYTES, label: 'theme logo' },
        warn,
      )
    : null;

  if (logoName) assets.push(`${THEME_ASSET_DIR}/${logoName}`);

  const customCssName = options.customCssPath
    ? await copyWorkspaceAsset(
        o.workspaceRoot,
        options.customCssPath,
        o.outputDir,
        'custom.css',
        { extensions: new Set(['.css']), maxBytes: THEME_CSS_LIMIT_BYTES, label: 'custom css' },
        warn,
      )
    : null;
  if (customCssName) assets.push(`${THEME_ASSET_DIR}/${customCssName}`);

  const rootIndexPath = join(o.outputDir, 'index.html');
  const rootTitle = existsSync(rootIndexPath)
    ? stripSiteSuffix(extractTitle(await readFile(rootIndexPath, 'utf8')), '')
    : '';
  const siteTitle = options.siteTitle ?? rootTitle;
  const footerText = options.footerText ?? '';

  const htmlFiles = await collectHtmlFiles(o.outputDir);
  const searchEntries: HtmlThemeSearchEntry[] = [];
  let pages = 0;

  for (const file of htmlFiles) {
    const relPath = toPosix(relative(o.outputDir, file));
    const html = await readFile(file, 'utf8');
    const entry = buildSearchEntry(relPath, html, siteTitle);
    // The map landing page is only a search result when it has real title content.
    if (relPath !== 'index.html' || entry.title) {
      searchEntries.push(entry);
    }

    const depth = depthOf(relPath);
    const context: InjectionContext = {
      themeId: o.themeId,
      relRoot: depth === 0 ? './' : '../'.repeat(depth),
      portal: relPath === 'index.html',
      siteTitle,
      footerText,
      defaultMode: descriptor.defaultMode,
      features,
      locale: o.locale,
      logoName,
      hasCustomCss: customCssName !== null,
    };
    const injected = injectPage(html, relPath, context, warn);
    if (injected === null) continue;
    await writeFile(file, injected, 'utf8');
    pages += 1;
  }

  searchEntries.sort((a, b) => (a.href < b.href ? -1 : a.href > b.href ? 1 : 0));
  await writeFile(
    join(assetDir, 'search-index.js'),
    `window.__DITA_SEARCH_INDEX__ = ${serializeInlineJson(searchEntries)};\n`,
    'utf8',
  );
  assets.push(`${THEME_ASSET_DIR}/search-index.js`);

  return {
    themeId: o.themeId,
    pages,
    assets,
    searchEntries,
    warnings,
    logo: logoName ? `${THEME_ASSET_DIR}/${logoName}` : null,
    customCss: customCssName ? `${THEME_ASSET_DIR}/${customCssName}` : null,
  };
}
