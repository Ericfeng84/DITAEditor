import { copyFile, mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { existsSync, statSync } from 'node:fs';
import { extname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import type { ApiLocale } from '../../i18n/locale.js';
import {
  accentScale,
  DEFAULT_HTML_FEATURES,
  getHtmlTheme,
  HTML_THEME_LABELS,
  resolveThemeOptions,
  type HtmlThemeFeatures,
  type HtmlThemeId,
  type HtmlThemeOptions,
} from './html-themes.js';

/**
 * Phase 12: deterministic post-processing for DITA-OT HTML5 output.
 *
 * DITA-OT keeps generating plain semantic HTML; this module adds the shared
 * styles, brand variables, header/footer chrome, the offline search index and
 * the zero-dependency runtime. No DITA-OT plugin has to be installed and no
 * absolute URL is ever emitted, so the zip keeps working from `file://` and
 * from the workbench preview route.
 */

export const THEME_ASSET_DIR = '_ditaeditor';

const THEME_LOGO_LIMIT_BYTES = 2 * 1024 * 1024;
const THEME_CSS_LIMIT_BYTES = 512 * 1024;
const SEARCH_TEXT_LIMIT = 4000;
const LOGO_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.svg', '.webp']);

export interface HtmlThemeSearchEntry {
  /** Output-root-relative POSIX href, e.g. `concepts/arch.html`. */
  href: string;
  title: string;
  summary: string;
  text: string;
}

export interface EnhanceHtml5Options {
  outputDir: string;
  themeId: HtmlThemeId;
  options: HtmlThemeOptions;
  themesDir: string;
  /** Workspace/branch snapshot root used to resolve logo and custom CSS paths. */
  workspaceRoot: string;
  locale: ApiLocale;
  onWarn?: (message: string) => void;
}

export interface Html5EnhanceResult {
  themeId: HtmlThemeId;
  pages: number;
  /** Files written below `_ditaeditor/`, as output-root-relative POSIX paths. */
  assets: string[];
  searchEntries: HtmlThemeSearchEntry[];
  warnings: string[];
  logo: string | null;
  customCss: string | null;
}

/* -------------------------------------------------------------------------- */
/* Escaping helpers                                                            */
/* -------------------------------------------------------------------------- */

const HTML_ENTITIES: Record<string, string> = {
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
  nbsp: ' ',
  mdash: '—',
  ndash: '–',
  hellip: '…',
  copy: '©',
  reg: '®',
  trade: '™',
};

export function escapeHtmlText(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * JSON safe for an inline `<script>`. `<` becomes `\u003c` so a `</script>`
 * inside a site title or footer can never terminate the block, and the two
 * JavaScript line separators are escaped for older engines.
 */
export function serializeInlineJson(value: unknown): string {
  return JSON.stringify(value)
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

